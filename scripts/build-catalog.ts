/**
 * Regenerates src/catalog-data.ts from endoflife.date (products with a CPE) plus
 * src/catalog-extra.ts (popular products endoflife.date doesn't track).
 *
 *   npm run catalog
 */
import { writeFile } from 'node:fs/promises';
import { EXTRA } from '../src/catalog-extra.js';

interface EolProduct {
  name: string;
  label: string;
  aliases: string[];
  identifiers: { type: string; id: string }[];
}

const response = await fetch('https://endoflife.date/api/v1/products/full', { headers: { 'user-agent': 'patchbell catalog builder' } });
if (!response.ok) throw new Error(`endoflife.date: HTTP ${response.status}`);
const { result } = (await response.json()) as { result: EolProduct[] };

const rows: [string, string, string[], string][] = [];
for (const product of result) {
  const cpe = product.identifiers.find((identifier) => identifier.type === 'cpe' && identifier.id.startsWith('cpe:2.3:'));
  if (!cpe) continue;
  const [, , part, vendor, name] = cpe.id.split(':');
  if (!part || !vendor || !name) continue;
  rows.push([product.name, product.label, product.aliases, `${part}:${vendor}:${name}`]);
}
rows.sort((a, b) => a[0].localeCompare(b[0]));

const known = new Set(rows.map((row) => row[0]));
const extra = EXTRA.filter((entry) => !known.has(entry.slug));

const source = `// Generated by scripts/build-catalog.ts from endoflife.date (MIT) on ${new Date().toISOString().slice(0, 10)}. Do not edit.
// [slug, label, aliases, "part:vendor:product"]
export const EOL_PRODUCTS: [string, string, string[], string][] = ${JSON.stringify(rows)};
`;
await writeFile(new URL('../src/catalog-data.ts', import.meta.url), source);
console.log(`${rows.length} endoflife.date products, ${extra.length} extra.`);
